// Generates src/styles/tokens.css from the design file's variables.
// The .pen source lives outside the repo (design-src is git-excluded), so
// pass its path explicitly or rely on the orchestrator's default location:
//   node scripts/gen-tokens.mjs [path/to/untitled.pen]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const penPath =
  process.argv[2] ??
  '/home/ryan/projects/wasm-playground-site/design-src/source/untitled.pen';
const pen = JSON.parse(readFileSync(penPath, 'utf8'));

const fallbacks = {
  'font-display': 'system-ui, sans-serif',
  'font-body': 'system-ui, sans-serif',
  'font-mono': 'ui-monospace, monospace',
};

const lines = Object.entries(pen.variables).map(([name, v]) => {
  if (v.type === 'color') return `  --${name}: ${v.value};`;
  const fallback = fallbacks[name] ? `, ${fallbacks[name]}` : '';
  return `  --${name}: '${v.value}'${fallback};`;
});

const css = `/* Generated by scripts/gen-tokens.mjs from untitled.pen variables. Do not edit by hand. */
:root {
${lines.join('\n')}
}
`;
writeFileSync(resolve(here, '../src/styles/tokens.css'), css);
console.log(css);
