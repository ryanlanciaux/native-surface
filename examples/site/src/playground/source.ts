// Real source text for the Source tab and the Code view: ignite-demo's own
// files, imported ?raw (lazily, one chunk per file), and the story module —
// the app's `*.stories.tsx`, or the CSF the catalog adapter generates.
import type { Args, PlaygroundArgType, PlaygroundItem } from './types';

const APP_ROOT = '../../../ignite-app/';
const files = import.meta.glob(['../../../ignite-app/{src,app}/**/*.{ts,tsx}', '!**/*.test.*', '!**/*.d.ts'], {
  query: '?raw',
  import: 'default',
}) as Record<string, () => Promise<string>>;

export interface SourceFile {
  /** Path inside the app, e.g. `src/components/EpisodeCard.tsx`. */
  file: string;
  text: string;
  /** Generated by the playground (no such file in the app). */
  generated?: boolean;
}

const display = (path: string) => path.replace(APP_ROOT, '');
const base = (path: string) => path.split('/').pop()!.replace(/\.(tsx?|jsx?)$/, '');

function componentName(item: PlaygroundItem): string | undefined {
  const c = item.group.stories[0]?.meta.component as { displayName?: string; name?: string } | undefined;
  return c?.displayName ?? c?.name;
}

/** The component's own file: matched by basename, preferring components/ then screens/. */
export function componentPath(item: PlaygroundItem): string | null {
  const names = [
    componentName(item),
    ...(item.parameters.sourceNames ?? []),
    item.name,
    item.name.replace(/^Demo/, ''),
  ].filter((n): n is string => !!n && !/^(observer|anonymous)$/i.test(n));
  const paths = Object.keys(files).filter((p) => !/\.stories\./.test(p));
  for (const name of names) {
    const hits = paths.filter((p) => base(p) === name);
    if (hits.length) return hits.sort((a, b) => rank(a) - rank(b))[0]!;
  }
  return null;
}
const rank = (p: string) => (/\/components\//.test(p) ? 0 : /\/screens\//.test(p) ? 1 : 2);

export async function loadComponentSource(item: PlaygroundItem): Promise<SourceFile | null> {
  const path = componentPath(item);
  return path ? { file: display(path), text: await files[path]!() } : null;
}

export async function loadStorySource(item: PlaygroundItem): Promise<SourceFile> {
  if (!item.parameters.catalog && files[item.path]) return { file: display(item.path), text: await files[item.path]!() };
  return { file: `${item.name}.stories.tsx`, text: generatedCsf(item), generated: true };
}

// ---------- generated CSF (catalog adapter) ----------

function lit(v: unknown, indent = ''): string {
  if (typeof v === 'string') {
    // Bundled asset URLs are long and build-specific; show the file.
    if (/^(\/|https?:|data:)/.test(v)) return `require('./assets/${v.split('/').pop()!.replace(/-[\w-]{8}(\.\w+)$/, '$1')}')`;
    return `'${v.replace(/'/g, "\\'")}'`;
  }
  if (typeof v === 'function') return 'fn()';
  if (v === undefined) return 'undefined';
  if (Array.isArray(v)) return `[${v.map((x) => lit(x, indent)).join(', ')}]`;
  if (v && typeof v === 'object') {
    const inner = `${indent}  `;
    const entries = Object.entries(v as Args).map(([k, x]) => `${inner}${/^[A-Za-z_$][\w$]*$/.test(k) ? k : `'${k}'`}: ${lit(x, inner)},`);
    return entries.length ? `{\n${entries.join('\n')}\n${indent}}` : '{}';
  }
  return String(v);
}

function argTypeLit(at: PlaygroundArgType): Record<string, unknown> {
  const out: Record<string, unknown> = { control: at.control };
  if (at.options) out.options = at.options;
  for (const k of ['min', 'max', 'step'] as const) if (at[k] !== undefined) out[k] = at[k];
  return out;
}

function generatedCsf(item: PlaygroundItem): string {
  const first = item.group.stories[0]!;
  const meta = first.meta;
  const args = meta.args ?? {};
  // Episodes come from the store, as in the app.
  const argsText = lit(
    Object.fromEntries(
      Object.entries(args).map(([k, v]) => [k, v && typeof v === 'object' && 'guid' in v ? STORE : v]),
    ),
    '  ',
  ).replace(`'${STORE}'`, 'episodeStore.episodes[0]');
  const argTypes = Object.fromEntries(
    Object.entries((meta.argTypes ?? {}) as Record<string, PlaygroundArgType>).map(([k, at]) => [k, argTypeLit(at)]),
  );
  const stories = item.group.stories
    .map((s) => `export const ${s.exportName}: Story = {${s.name !== s.exportName ? ` name: '${s.name}',` : ''} args: ${lit(s.story.args ?? {})} }`)
    .join('\n');
  return `// Generated by the playground from ignite-demo's component catalog
// (${item.name} has no .stories.tsx yet). Loaded through the same CSF
// loader as the app's own story files.
import type { Meta, StoryObj } from '@storybook/react'
import { fn } from '@storybook/test'
import { ${item.name}, episodeStore } from 'ignite-demo'

const meta = {
  title: '${meta.title}',
  component: ${item.name},
  args: ${argsText},
  argTypes: ${lit(argTypes, '  ')},
} satisfies Meta<typeof ${item.name}>

export default meta
type Story = StoryObj<typeof meta>

${stories}
`;
}
const STORE = '__episodeStore__';
